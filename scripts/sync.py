#!/usr/bin/env python3
"""Synchronize this checkout's skills, commands, and Claude mods.

The script is deliberately opt-in: without --apply it only discovers harnesses
and prints the proposed targets. Existing real files are never overwritten.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HOME = Path.home()

HARNESS_HOMES = {
    "claude": HOME / ".claude",
    "opencode": HOME / ".config" / "opencode",
    "codex": HOME / ".codex",
    "antigravity": HOME / ".gemini",
    "copilot": HOME / ".copilot",
    "cursor": HOME / ".cursor",
    "kiro": HOME / ".kiro",
}
SUPPORTED = {"claude", "opencode", "codex", "antigravity"}


def is_link(path: Path) -> bool:
    is_junction = getattr(path, "is_junction", lambda: False)
    return path.is_symlink() or is_junction()


def discover() -> dict[str, bool]:
    result = {}
    for name, path in HARNESS_HOMES.items():
        try:
            result[name] = path.exists()
        except OSError:
            result[name] = False
    return result


def link_directory(source: Path, target: Path, label: str, apply: bool) -> str:
    if not source.is_dir():
        return f"SKIP {label}: source missing ({source})"
    if target.exists() or target.is_symlink():
        if is_link(target):
            try:
                if target.resolve() == source.resolve():
                    return f"OK {label}: already linked"
            except OSError:
                pass
        return f"SKIP {label}: target exists and is not this link ({target})"
    if not apply:
        return f"PLAN {label}: {target} -> {source}"
    target.parent.mkdir(parents=True, exist_ok=True)
    if os.name == "nt":
        subprocess.run(
            ["cmd", "/c", "mklink", "/J", str(target), str(source)],
            check=True,
            stdout=subprocess.DEVNULL,
        )
    else:
        target.symlink_to(source, target_is_directory=True)
    return f"LINK {label}: {target} -> {source}"


def source_skills() -> list[Path]:
    base = ROOT / "skills"
    return sorted(p for p in base.iterdir() if p.is_dir() and (p / "SKILL.md").exists()) if base.exists() else []


def source_mods() -> list[Path]:
    base = ROOT / "mods"
    return sorted(p for p in base.iterdir() if p.is_dir()) if base.exists() else []


def canonical_link_issues() -> list[Path]:
    issues: list[Path] = []
    for base in (ROOT / "skills", ROOT / "mods"):
        if not base.exists():
            continue
        issues.extend(p for p in base.iterdir() if p.is_dir() and is_link(p))
    return sorted(issues)


def sync_harness(name: str, apply: bool) -> list[str]:
    shared_skills = ROOT / "skills"
    shared_commands = ROOT / "commands"
    out: list[str] = []
    if name == "codex":
        out.append(f"OK codex: reads {shared_skills} directly")
    elif name == "antigravity":
        out.append(link_directory(shared_skills, HOME / ".gemini" / "config" / "skills", "antigravity skills", apply))
    elif name in {"claude", "opencode"}:
        skill_target = HOME / (".claude" if name == "claude" else ".config/opencode") / "skills"
        command_target = HOME / (".claude" if name == "claude" else ".config/opencode") / "commands"
        for skill in source_skills():
            out.append(link_directory(skill, skill_target / skill.name, f"{name} skill {skill.name}", apply))
        out.append(link_directory(shared_commands, command_target, f"{name} commands", apply))
    if name == "claude":
        mod_target = HOME / ".claude" / "mods"
        for mod in source_mods():
            out.append(link_directory(mod, mod_target / mod.name, f"Claude mod {mod.name}", apply))
    return out


def refresh_inventory() -> None:
    inventory = ROOT / "scripts" / "inventory.py"
    subprocess.run([sys.executable, str(inventory)], cwd=ROOT, check=False)


def refresh_index() -> None:
    skills = source_skills()
    mods = source_mods()
    lines = [
        "# Orchestration index",
        "",
        "This checklist is generated by `python scripts/sync.py --apply`. Run it after",
        "adding a skill, command, or mod so the laptop agent can see the current set.",
        "",
        "## Sync checklist",
        "",
        "- [ ] Discover installed AI harnesses.",
        "- [ ] Ask the user which detected harnesses to configure.",
        "- [ ] Link every source skill to the selected harnesses.",
        "- [ ] Link shared commands where the harness supports them.",
        "- [ ] Link every tracked Claude mod, preserving its plugin manifest and hooks.",
        "- [ ] Run `scripts/inventory.py` and inspect broken links or duplicates.",
        "- [ ] Restart the selected desktop agents.",
        "",
        f"## Skills ({len(skills)})",
        "",
    ]
    lines.extend(f"- [ ] `{skill.name}` — `{skill.relative_to(ROOT)}`" for skill in skills)
    lines.extend(["", f"## Claude mods ({len(mods)})", ""])
    lines.extend(f"- [ ] `{mod.name}` — `{mod.relative_to(ROOT)}`" for mod in mods)
    if not mods:
        lines.append("- [ ] No tracked Claude mods. Add a complete mod under `mods/<name>` to distribute it.")
    lines.extend(["", "## Source directories", "", "- Skills: `skills/<name>/SKILL.md`", "- Commands: `commands/`", "- Mods: `mods/<name>/.claude-plugin/plugin.json` plus hook files when needed", ""])
    (ROOT / "INDEX.md").write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--harness", help="comma-separated harnesses: claude,opencode,codex,antigravity")
    parser.add_argument("--apply", action="store_true", help="create links and refresh inventory/index")
    parser.add_argument("--refresh-index", action="store_true", help="refresh INDEX.md without changing links")
    args = parser.parse_args()
    found = discover()
    print(json.dumps({"detected": found, "supported": sorted(SUPPORTED)}, indent=2))
    if args.refresh_index:
        refresh_index()
        print("Refreshed INDEX.md.")
        return 0
    issues = canonical_link_issues()
    if issues:
        print("ERROR: canonical .agents sources must be real directories; links found:", file=sys.stderr)
        for issue in issues:
            print(f"- {issue}", file=sys.stderr)
        return 2
    selected = [h.strip().lower() for h in args.harness.split(",")] if args.harness else []
    if not selected:
        print("Ask the user which detected supported harnesses to configure, then rerun with --harness ... --apply.")
        return 0
    invalid = sorted(set(selected) - SUPPORTED)
    if invalid:
        print(f"ERROR unsupported harness: {', '.join(invalid)}", file=sys.stderr)
        return 2
    for harness in selected:
        print(f"## {harness}")
        for line in sync_harness(harness, args.apply):
            print(line)
    if args.apply:
        refresh_inventory()
        refresh_index()
        print("Refreshed manifests and INDEX.md. Restart configured desktop agents.")
    else:
        print("Dry run only. Add --apply after the user confirms the harness selection.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
